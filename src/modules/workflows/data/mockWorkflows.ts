// Helper function to get workflow by ID
export function getWorkflowById(id: string): Workflow | undefined {
  return mockWorkflows.find((w) => w.id === id);
}

// Helper function to format actions for display
export function formatActions(actions: WorkflowAction[]): string {
  const labels: Record<WorkflowAction, string> = {
    publish: "Publish",
    edit_metadata: "Edit Metadata",
    delete: "Delete",
    assign_steward: "Assign Steward",
    export: "Export",
    access_grant: "Access Grant",
  };
  return actions.map((a) => labels[a]).join(", ");
}

// Helper function to format approvers for display
export function formatApprovers(approvers: { name: string; role: string }[]): string {
  return approvers.map((a) => `${a.role}`).join(", ");
}

